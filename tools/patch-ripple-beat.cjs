/*
 * 涟漪跟上音乐节奏。
 *
 * 用户："跟上音乐的节奏啊"
 *
 * 我前几版把节拍项全删了 ✗ —— 那是对他那句"我要的不是跳动"的过度反应。
 * 他要的不是"整个画面跟着鼓点缩放一下"（那是 applyBeat 干的），
 * 而是**效果本身对音乐有反应**。
 *
 * ★ 而 effects.js 里**早就为此准备好了机制**：
 *
 *   uBeatAge（距上次鼓点过去多少秒）的注释原文：
 *     「只有 uPulse 时，效果最多只能做"整体鼓一下"；有了 uBeatAge 就能做
 *       **按时间展开的行波** —— 涟漪从中心一圈圈荡开、冲击波向外扩张、
 *       极光沿着帷幕扫过去。这种"事件向外传播"的观感比整体缩放高级得多，
 *       也更贴节奏。」
 *
 *   这段注释简直就是在描述涟漪 ✗→✓ 我却一直没用它。
 *
 * 所以这一版：
 *   ① **基础涟漪**：恒定、舒缓，保证没鼓点的时候画面也是活的
 *   ② **鼓点环**：每一下鼓点从中心放出一圈，按 uBeatAge 向外扩张、
 *      越荡越弱 —— 这是"跟上节奏"的主体
 *   ③ **低音驱动幅度**：uBeatAmp 抬基础涟漪的起伏
 *
 * ★ 注意仍然**不调用 applyBeat()** —— 那是"整张结构径向鼓出"，
 *   会让整片涟漪一起缩放，正是用户嫌弃的那种"画面呼吸" ✗
 */
const fs = require('node:fs');
const path = require('node:path');
const f = path.join(__dirname, '..', 'apps', 'ui', 'src', 'effects.js');
let t = fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n');
const log = (m) => console.log(m);
let n = 0;
const rep = (a, b, label) => {
  if (t.includes(a)) {
    t = t.replace(a, b);
    n++;
  } else log('!! ' + label);
};

// ① 波形：基础涟漪 + 鼓点环 + 低音幅度
rep(
  `        /*
         * 涟漪：以到圆心的距离为相位。
         *   aRad * 1.15  → 波长约 5.5 世界单位（画面里能看到 2~3 圈）
         *   uTime * 0.85 → 一圈从中心荡到边缘约 13 秒，很慢
         * 减号表示**向外传播**（加号是向内收）。
         */
        float w = sin(aRad * 1.15 - uTime * 0.85);

        /*
         * 第二层更慢、波长更长的波，做"大浪叠小浪"。
         * 单层正弦太规整，看着像同心圆靶子而不是水面。
         */
        w = w * 0.7 + sin(aRad * 0.52 - uTime * 0.47 + 1.3) * 0.3;

        /*
         * ★ 不调 applyBeat()，也不读 uBeatAmp / uPulse。
         * 用户明确说过："我要的不是跳动啊，是粒子效果" ——
         * 涟漪的节奏是波自己荡开，不该由鼓点驱动。
         */`,
  `        /*
         * ① 基础涟漪：恒定、舒缓。
         *    aRad * 1.15  → 波长约 5.5 世界单位（画面里约 3 圈）
         *    uTime * 0.85 → 一圈荡到边缘约 13 秒
         *    减号 = 向外传播。
         *    两层叠加（第二层更慢更长）避免单层正弦那种"同心圆靶子"感。
         */
        float base = sin(aRad * 1.15 - uTime * 0.85) * 0.7
                   + sin(aRad * 0.52 - uTime * 0.47 + 1.3) * 0.3;

        /*
         * ② 鼓点环 —— "跟上节奏"的主体。
         *
         *    uBeatAge = 距上一次鼓点过去了多少秒（由主循环维护）。
         *    波前半径 = 年龄 × 速度，于是每一拍都会有一圈**从中心向外荡开**。
         *    高斯包络让它是一"圈"而不是一团：
         *      exp(-((r - front) * 0.85)^2)  —— 离波前越远衰减越快。
         *    再乘一个随时间衰减的系数：越荡越弱，不会越积越乱。
         *
         *    这就是 uBeatAge 注释里说的"事件向外传播"，
         *    比"整体鼓一下"高级得多，也更贴节奏。
         */
        float front = uBeatAge * 5.5;
        float ring = exp(-pow((aRad - front) * 0.85, 2.0)) * exp(-uBeatAge * 0.9);

        /*
         * ③ 低音抬基础起伏的幅度。
         *    注意：是抬**幅度**，不是把整片缩放 —— 后者就是用户嫌弃的
         *    "画面呼吸跳动"。所以这里**不调用 applyBeat()**。
         */
        float w = base * (0.55 + uBeatAmp * 0.65) + ring * 1.5;`,
  '波形'
);

// ② 亮度：鼓点环要明显
rep(
  `        float crest = smoothstep(-0.75, 0.95, w);`,
  `        /*
         * 波峰判定。鼓点环的 w 峰值远高于基础波（1.5 vs 约 1.0），
         * 所以同一套 smoothstep 会让"鼓点那一圈"明显更亮 —— 正是要的效果。
         */
        float crest = smoothstep(-0.75, 0.95, w);`,
  '亮度说明'
);

fs.writeFileSync(f, t.replace(/\n/g, '\r\n'));
log('改了 ' + n + ' 处');
